# Problem 38.1 - Most Weekly Sales
# Given an array sales, find the most sales in any 7-day period.
#
# Example 1: sales = [0,3,7,12,10,5,0,1,0,15,12,11,1] -> 44
# Example 2: sales = [0,3,7,12] -> 0 (no 7-day period)
# Example 3: sales = [1,2,3,4,5,6,7] -> 28
#
# Constraints:
# - len(sales) <= 10^6
# - Each element is a non-negative integer < 10^3