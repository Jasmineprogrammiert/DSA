# Problem 38.7 - Longest Alternating Sequence
# Given array sales, find the longest sequence alternating between good and
# bad days. Good day >= 10 sales, bad day < 10.
#
# Example 1: sales = [8,9,20,0,9] -> 3 ([9,20,0])
# Example 2: sales = [0,0,0] -> 1
# Example 3: sales = [5,10,5,10] -> 4
#
# Constraints:
# - 0 <= len(sales) <= 10^5
# - 0 <= sales[i] <= 10^3