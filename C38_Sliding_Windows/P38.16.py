# Problem 38.16 - Smallest Range With k Elements
# Given an array of integers and k (1 <= k <= len(arr)), return [low, high]
# representing the smallest range containing at least k elements.
#
# Example 1: arr = [1,2,5,7,8], k = 3 -> [5,8]
# Example 2: arr = [5,5,2,2,8,8], k = 3 -> [2,5]
# Example 3: arr = [0], k = 1 -> [0,0]
#
# Constraints:
# - 1 <= k <= len(arr) <= 10^5
# - -10^9 <= arr[i] <= 10^9