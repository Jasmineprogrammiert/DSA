# Problem 38.6 - Max Subarray Sum
# Given a non-empty array of integers (can be negative), find the non-empty
# subarray with the maximum sum and return its sum.
#
# Example 1: arr = [1,2,3,-2,1] -> 6
# Example 2: arr = [1,2,3,-2,7] -> 11
# Example 3: arr = [1,2,3,-8,7] -> 7
# Example 4: arr = [-2,-3,-4] -> -2
#
# Constraints:
# - 1 <= len(arr) <= 10^5
# - -10^6 <= arr[i] <= 10^6