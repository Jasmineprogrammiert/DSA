# Problem 38.8 - Maximum With at Most 3 Bad Days
# Given array sales, find the most consecutive days with at most 3 bad days.
# A bad day has fewer than 10 sales.
#
# Example 1: sales = [0,14,7,9,0,20,10,0,10] -> 6
# Example 2: sales = [10,10,10] -> 3
# Example 3: sales = [5,5,5,5] -> 3
#
# Constraints:
# - 0 <= len(sales) <= 10^5
# - 0 <= sales[i] <= 10^3