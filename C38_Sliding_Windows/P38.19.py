# Problem 38.19 - Count Subarrays With Exactly k Bad Days
# Count subarrays with exactly k bad days (bad day < 10 sales).
#
# Example 1: sales = [0,20,5], k = 1 -> 4
# Example 2: sales = [10,20,30], k = 1 -> 0
# Example 3: sales = [0,5,8], k = 2 -> 2
#
# Constraints:
# - 0 <= sales.length <= 10^5
# - 0 <= k <= 10^5