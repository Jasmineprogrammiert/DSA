# Problem 38.2 - Most Sales in k Days
# Given array sales and number k (1 <= k <= len(sales)), find the most sales
# in any k-day period. Return the first day of that period (0-indexed).
# If ties, return the first one.
#
# Example 1: sales = [8,1,3,7], k = 2 -> 2
# Example 2: sales = [5,10,15,5], k = 1 -> 2
# Example 3: sales = [1,2,3], k = 3 -> 0
#
# Constraints:
# - len(sales) <= 10^6
# - 1 <= k <= len(sales)