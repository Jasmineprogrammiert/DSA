# Problem 38.5 - Longest Good Day Streak
# Given an array sales, find the most consecutive days with no bad days.
# A bad day has fewer than 10 sales.
#
# Example 1: sales = [0,14,7,12,10,20] -> 3 ([12,10,20])
# Example 2: sales = [10,10,10] -> 3
# Example 3: sales = [5,5,5] -> 0
#
# Constraints:
# - 0 <= len(sales) <= 10^5
# - 0 <= sales[i] <= 10^3