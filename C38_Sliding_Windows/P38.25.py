# Problem 38.25 - Count Good Subarrays With at Least k Sales
# Count subarrays with no bad days and at least k total sales.
# Bad day < 10 sales.
#
# Example 1: sales = [15,20,5,30,25], k = 50 -> 1
# Example 2: sales = [10,20,30], k = 40 -> 2
# Example 3: sales = [0,5,8], k = 10 -> 0
#
# Constraints:
# - 0 <= sales.length <= 10^5
# - 0 <= sales[i] <= 10^3
# - 1 <= k <= 10^7