# Problem 38.20 - Count Subarrays With at Least k Bad Days
# Count subarrays with at least k bad days (bad day < 10 sales).
#
# Example 1: sales = [0,20,5], k = 1 -> 5
# Example 2: sales = [10,20,30], k = 1 -> 0
# Example 3: sales = [0,5,8], k = 2 -> 3
#
# Constraints:
# - 0 <= sales.length <= 10^5
# - 0 <= k <= 10^5