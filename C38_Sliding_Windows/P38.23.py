# Problem 38.23 - Count Subarrays With Bad Days in Range
# Count subarrays with at least k1 and at most k2 bad days.
# Bad day < 10 sales.
#
# Example 1: sales = [0,20,5], k1 = 2, k2 = 2 -> 1
# Example 2: sales = [0,20,5], k1 = 1, k2 = 2 -> 5
# Example 3: sales = [10,20,30], k1 = 1, k2 = 2 -> 0
#
# Constraints:
# - 0 <= sales.length <= 10^5
# - 0 <= k1 <= k2 <= 10^5