# Problem 38.14 - Shortest Period With Over 20 Sales
# Given array sales, find the shortest period with over 20 sales, or -1.
#
# Example 1: sales = [5,10,15,5,10] -> 2 ([10,15])
# Example 2: sales = [5,10,4,5,10] -> 4
# Example 3: sales = [5,5,5,5] -> -1
#
# Constraints:
# - 0 <= len(sales) <= 10^5
# - 0 <= sales[i] <= 10^3