# Problem 38.18 - Count Subarrays With at Most k Bad Days
# Count subarrays with at most k bad days (bad day < 10 sales).
#
# Example 1: sales = [0,20,5], k = 1 -> 5
# Example 2: sales = [10,20,30], k = 1 -> 6
# Example 3: sales = [0,5,8], k = 1 -> 3
#
# Constraints:
# - 0 <= sales.length <= 10^5
# - 0 <= k <= 10^5