# Problem 38.24 - Count Subarrays With All Remainders
# Count subarrays that have at least one multiple of 3, one number with
# remainder 1 mod 3, and one with remainder 2 mod 3.
#
# Example 1: arr = [9,8,7] -> 1
# Example 2: arr = [1,2,3,4,5] -> 6
# Example 3: arr = [1,3,4,6,7,9] -> 0
#
# Constraints:
# - 0 <= arr.length <= 10^5
# - 1 <= arr[i] <= 10^9