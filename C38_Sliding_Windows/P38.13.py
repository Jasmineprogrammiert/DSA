# Problem 38.13 - Longest Repeated Substring
# Given a string s, return the longest substring that appears more than once
# (overlapping allowed), or "" if none.
#
# Example 1: s = "murmur" -> "mur"
# Example 2: s = "murmurmur" -> "murmur"
# Example 3: s = "aaaa" -> "aaa"
#
# Constraints:
# - 0 <= len(s) <= 10^5
# - Lowercase English letters only