# Problem 38.15 - Shortest With All Letters
# Given s1 and a shorter non-empty s2, return the length of the shortest
# substring of s1 containing every letter in s2 at least as many times.
# Return -1 if impossible.
#
# Example 1: s1 = "helloworld", s2 = "well" -> 5 ("ellow")
# Example 2: s1 = "helloworld", s2 = "weelll" -> -1
#
# Constraints:
# - 1 <= len(s2) < len(s1) <= 10^5
# - Lowercase English letters