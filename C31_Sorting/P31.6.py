# Problem 31.6 - First K
# Given an array of n unique integers, return the k smallest numbers in any order.
#
# Example: arr = [15, 4, 13, 8, 10, 5, 2, 20, 3, 9, 11, 27], k = 5 -> [4, 3, 2, 5, 8]
#
# Constraints:
# - 0 <= k <= n <= 10^5
# - All elements in arr are unique
# - Each element between -10^9 and 10^9