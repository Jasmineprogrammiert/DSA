# Problem 31.1 - Sorting by Frequency
# Given a string of lowercase letters, return a sorted array with all letters
# sorted from most frequent to least frequent.
# Tie-break: alphabetical order.
#
# Example: "aabbbcccc" -> ['c', 'b', 'a']
#
# Constraints:
# - len(word) <= 10^5
# - word contains only lowercase letters