# Problem 40.4 - Count 0-Sum Paths
# Given a non-empty RxC binary grid, count paths from top-left to bottom-right
# with sum 0. Can go down, right, or diagonally down-right.
#
# Example 1:
# grid = [[0,1,1],[0,0,0],[1,0,0]] -> 7
#
# Example 2: grid = [[1]] -> 0
# Example 3: grid = [[0,0],[0,0]] -> 3
#
# Constraints:
# - 1 <= R, C <= 1000
# - grid[i][j] is 0 or 1