# Problem 40.1 - Road Trip
# Given n rest stops with delay times, can't go more than 2 stops without
# a break. Find minimum detour time.
#
# Example 1: times = [8,1,2,3,9,6,2,4] -> 6 (stop at 1,3,2)
# Example 2: times = [8,1,2,3,9,3,2,4] -> 5
# Example 3: times = [10,10] -> 0
# Example 4: times = [10] -> 0
# Example 5: times = [] -> 0
#
# Constraints:
# - 0 <= n <= 10^6
# - 1 <= times[i] <= 10^3