# Problem 40.6 - Minimum Steps to One
# Given positive integer n, return minimum operations to reach 1:
# - Subtract 1
# - Divide by 2 (if divisible)
# - Divide by 3 (if divisible)
#
# Example 1: n = 10 -> 3 (10->9->3->1)
# Example 2: n = 1 -> 0
# Example 3: n = 15 -> 4
#
# Constraints:
# - 1 <= n <= 10^6