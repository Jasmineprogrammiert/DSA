# Problem 40.8 - Reconstruct Longest Common Subsequence
# Given two strings s1 and s2, return the longest common subsequence string.
# Ties: return any.
#
# Example 1: s1 = "HAHAH", s2 = "AAAAHH" -> "AAH" (or "AHH")
# Example 2: s1 = "", s2 = "AA" -> ""
# Example 3: s1 = "ABCD", s2 = "ACBAD" -> "ACD" (or "ABD")
#
# Constraints:
# - len(s1), len(s2) <= 1000
# - Uppercase English letters only