# Problem 40.7 - Longest Common Subsequence
# Given two strings s1 and s2, return the length of the longest common
# subsequence. A subsequence appears in same relative order but not
# necessarily consecutively.
#
# Example 1: s1 = "HAHAH", s2 = "AAAAHH" -> 3 ("AAH" or "AHH")
# Example 2: s1 = "", s2 = "AA" -> 0
# Example 3: s1 = "ABC", s2 = "BCA" -> 2 ("BC")
#
# Constraints:
# - 0 <= len(s1), len(s2) <= 1000
# - Uppercase English letters only