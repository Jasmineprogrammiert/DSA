# Problem 34.13 - Duplicate Removal in Sorted Linked List
# Given the head of a singly linked list with sorted integer values, remove
# duplicates in place.
#
# Example 1:
# head = 1 -> 1 -> 1 -> 3 -> 5 -> 5 -> null
# Output: 1 -> 3 -> 5 -> null
#
# Example 2:
# head = 1 -> 1 -> 1 -> 1 -> 1 -> null
# Output: 1 -> null
#
# Example 3:
# head = null
# Output: null
#
# Constraints:
# - Create Node class with integer val field and next pointer
# - Up to 10^5 nodes