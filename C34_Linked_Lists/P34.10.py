# Problem 34.10 - Linked-List Midpoint
# Given the head of a non-empty singly linked list, return the value in the
# middle. If there is an even number of nodes, return the value of the right
# middle node.
#
# Example 1: 10 -> 20 -> 30 -> null => 20
# Example 2: 10 -> 20 -> 30 -> 40 -> null => 30
# Example 3: 10 -> null => 10
#
# Follow-up: Can you do it without computing the length of the list first?
#
# Constraints:
# - Create Node class with integer val field and next pointer
# - 1 <= nodes <= 10^5