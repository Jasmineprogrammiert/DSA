# Find a password that: has 1-10 letters, lowercase only, no repeated letters.
# You can call check_password(s) to test. Find the password.
#
# Example:
# check_password("a")   -> False
# check_password("abc") -> False
# check_password("bc")  -> True
# Output: "bc"
#
# Constraints:
# - No explicit limit on check_password() calls