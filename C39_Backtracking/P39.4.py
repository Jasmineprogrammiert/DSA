# Problem 39.4 - To Be or Not to Be
# Given a string of words, for each word choose to include or exclude it.
# Return all possible outcomes.
#
# Example 1: sentence = "I love dogs"
# Output: ["","I","love","dogs","I love","I dogs","love dogs","I love dogs"]
#
# Example 2: sentence = "hello" -> ["","hello"]
# Example 3: sentence = "" -> [""]
#
# Constraints:
# - Lowercase letters and spaces
# - At most 12 words, at most 100 characters