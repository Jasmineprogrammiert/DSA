# Problem 39.3 - Permutation Enumeration
# Given an array of unique characters arr, return all possible permutations.
#
# Example 1: arr = ['x','y','z']
# Output: [['x','y','z'],['x','z','y'],['y','x','z'],
#          ['y','z','x'],['z','x','y'],['z','y','x']]
#
# Example 2: arr = ['x'] -> [['x']]
#
# Constraints:
# - Elements are unique
# - len(arr) <= 10