# Problem 39.1 - Max-Sum Path
# Given a non-empty grid of positive integers, find the path from top-left
# to bottom-right with the largest sum. Can only go down or right.
#
# Example 1: grid = [[1,4,3],[2,7,6],[5,8,9]] -> 29 (1->4->7->8->9)
# Example 2: grid = [[5]] -> 5
# Example 3: grid = [[1,2,3]] -> 6
#
# Constraints:
# - 1 <= R, C <= 1000
# - 1 <= grid[i][j] <= 1000