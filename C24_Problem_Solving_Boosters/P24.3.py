# # List of Divisors

# Given a positive integer `n`, find all its divisors in ascending order.

# A divisor (or factor) of a number `n` is an integer that divides `n` evenly (with no remainder).

# Example 1: n = 40
# Output: [1, 2, 4, 5, 8, 10, 20, 40]

# Example 2: n = 1
# Output: [1]

# Example 3: n = 17
# Output: [1, 17]

# Constraints:

# - `1 <= n <= 10^9`