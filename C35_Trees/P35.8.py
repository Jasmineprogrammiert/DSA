# Problem 35.8 - Left View
# Given the root of a binary tree, return its left view. The left view is an
# array with the value of the first node on each layer, ordered top to bottom.
#
# Example:
#     1
#    / \
#   2   3
#    \   \
#     5   6
#          \
#           7
# Output: [1, 2, 5, 7]
#
# Constraints:
# - Number of nodes <= 10^5
# - Node values between 0 and 10^9