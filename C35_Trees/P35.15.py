# Problem 35.15 - BST Duplicate Detection
# Given the root of a BST, determine if it contains any duplicate values.
#
# Example:
#               5
#             /    \
#            2      9
#             \    / \
#              4  9   11
#                  \
#                   9
# Output: True
#
# Constraints:
# - Number of nodes <= 10^5
# - Height <= 500
# - Node values between 0 and 10^9