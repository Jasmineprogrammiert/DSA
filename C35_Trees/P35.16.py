# Problem 35.16 - BST Kth Element
# Given the root of a BST with n nodes, find the k-th smallest element
# (0-indexed), where 0 <= k <= n-1.
#
# Example 1:
#               5
#             /    \
#            2      9
#             \    / \
#              4  9   11
# k = 4 -> 9
#
# Example 2: same tree, k = 0 -> 2
#
# Constraints:
# - Number of nodes <= 10^5
# - Height <= 500
# - Node values between 0 and 10^9
# - 0 <= k <= n-1