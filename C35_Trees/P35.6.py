# Problem 35.6 - Invert a Binary Tree
# Given a binary tree, invert it by modifying the left and right pointers
# (do not modify values or create new nodes). Return the root.
#
# Example:
#      1             1
#    /   \         /   \
#   6     7  =>   7     6
#  / \   /         \   / \
# 4  11 2           2 11  4
#  \     \         /     /
#   5     9       9     5
#
# Constraints:
# - Number of nodes <= 10^5
# - Height <= 500
# - Node values between 0 and 10^9