# Problem 35.10 - Zig-Zag Order
# Given a binary tree, return the values of all nodes in zig-zag order.
# Similar to level-order but alternating direction at each level.
# Even depth: left to right. Odd depth: right to left.
#
# Example:
#     1
#    / \
#   2   3
#  / \   \
# 4   5   6
# Output: [1, 3, 2, 4, 5, 6]
#
# Constraints:
# - Number of nodes <= 10^5
# - Node values between 0 and 10^9