# Problem 32.6 - Balanced Partition
# Given a balanced parentheses string s, a balanced partition is a partition of s
# into substrings, each of which is itself balanced. Return the maximum possible
# number of substrings in a balanced partition.
#
# Example: s = "((()))(()())()(()(()))" -> 4
# Partition: "((()))", "(()())", "()", "(()(()))"
#
# Constraints:
# - len(s) <= 10^5
# - s consists only of '(' and ')'